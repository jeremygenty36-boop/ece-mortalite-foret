# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# Diagnostic NA E-OBS - % de NA sur la France par jour
# Période  : un mois paramétrable (défaut : mars 1981)
# Auteur   : JeremyG - Projet EvenementsExtremes
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

# Chemins : config/chemins.R (lancer depuis la racine du depot, ou definir ECE_DEPOT)
if (!exists("DEPOT")) source(file.path(Sys.getenv("ECE_DEPOT", getwd()), "config", "chemins.R"))
library(terra)
library(ggplot2)

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# PARAMÈTRES
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

dir_eobs <- file.path("S:", "Projets", "stage_JeremyG",
                      "3-Donnees", "3-E_OBS", "2-1950_2024_EOBS_FR")

dir_out  <- file.path("S:", "Projets", "stage_JeremyG",
                      "3-Donnees", "3-E_OBS", "diagnostics_NA")

# Mois et année à analyser
annee_diag <- 1981
mois_diag  <- 3    # mars

# Variable à analyser (rr, tn, tx)
var_diag <- "rr"
fichier_nc <- switch(var_diag,
                     "rr" = "rr_ens_mean_0.1deg_reg_v31.0e.nc",
                     "tn" = "tn_ens_mean_0.1deg_reg_v31.0e.nc",
                     "tx" = "tx_ens_mean_0.1deg_reg_v31.0e.nc"
)

# Masque France (vecteur polygone pour calculer le % de NA uniquement
# sur la France, pas sur toute l'emprise du fichier E-OBS)
# On utilise rnaturalearth si disponible, sinon emprise manuelle
utiliser_masque_france <- TRUE

if (!dir.exists(dir_out)) dir.create(dir_out, recursive = TRUE)

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# CHARGEMENT
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

f_nc <- file.path(dir_eobs, fichier_nc)
if (!file.exists(f_nc)) stop("Fichier introuvable : ", f_nc)

cat("Chargement E-OBS (lazy)...\n")
r_all        <- rast(f_nc)
date_origine <- as.Date("1950-01-01")
dates_all    <- date_origine + 0:(nlyr(r_all) - 1)

# Sélectionner les jours du mois demandé
idx_mois  <- which(format(dates_all, "%Y-%m") ==
                     sprintf("%d-%02d", annee_diag, mois_diag))

if (length(idx_mois) == 0)
  stop(sprintf("Aucune donnée pour %02d/%d", mois_diag, annee_diag))

dates_mois <- dates_all[idx_mois]
r_mois     <- r_all[[idx_mois]]

cat(sprintf("Jours sélectionnés : %d  (%s ??? %s)\n",
            length(idx_mois),
            format(min(dates_mois), "%d/%m/%Y"),
            format(max(dates_mois), "%d/%m/%Y")))

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# MASQUE FRANCE
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

if (utiliser_masque_france) {
  # Essayer rnaturalearth, sinon emprise manuelle
  france_vect <- tryCatch({
    library(rnaturalearth)
    fr <- ne_countries(country = "France", scale = "medium",
                       returnclass = "sv")
    # Buffer de 0.15° (~15 km) pour inclure les pixels côtiers E-OBS
    # (à 0.1° un pixel fait ~11 km, souvent à cheval terre/mer)
    buffer(fr, width = 0.15)
  }, error = function(e) {
    cat("rnaturalearth absent ??? emprise manuelle élargie\n")
    as.polygons(ext(-6, 10, 41, 52), crs = "EPSG:4326")
  })
  
  # Rogner E-OBS sur l'emprise France + buffer
  r_france <- crop(r_mois, france_vect)
  # touches = TRUE : inclut les pixels qui touchent le bord du polygone
  r_france <- mask(r_france, france_vect, touches = TRUE)
  
  cat(sprintf("Pixels dans le masque France : %d\n", ncell(r_france)))
} else {
  r_france <- r_mois
}

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# CALCUL DU % DE NA PAR JOUR
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

cat("\nCalcul % NA par jour...\n")

n_pixels_france <- sum(!is.na(values(r_france[[1]])) |
                         is.na(values(r_france[[1]])))
# Plus robuste : compter les pixels dans l'emprise masquée
vals_ref <- values(r_france[[1]])
n_pixels_masque <- length(vals_ref[!is.nan(vals_ref)])

resultats <- data.frame(
  date    = dates_mois,
  jour    = as.integer(format(dates_mois, "%d")),
  n_na    = NA_integer_,
  n_total = NA_integer_,
  pct_na  = NA_real_
)

for (i in seq_len(nlyr(r_france))) {
  vals    <- values(r_france[[i]])
  n_total <- length(vals)
  n_na    <- sum(is.na(vals))
  
  resultats$n_na[i]    <- n_na
  resultats$n_total[i] <- n_total
  resultats$pct_na[i]  <- round(n_na / n_total * 100, 1)
}

# Afficher le tableau
cat("\n?????? % NA par jour sur la France ??????????????????????????????????????????????????????\n")
cat(sprintf("%-12s  %6s  %6s  %8s\n",
            "Date", "N_NA", "N_tot", "% NA"))
cat(strrep("-", 38), "\n")
for (i in seq_len(nrow(resultats))) {
  cat(sprintf("%-12s  %6d  %6d  %7.1f%%\n",
              format(resultats$date[i], "%d/%m/%Y"),
              resultats$n_na[i],
              resultats$n_total[i],
              resultats$pct_na[i]))
}
cat(strrep("-", 38), "\n")
cat(sprintf("Moyenne mensuelle : %.1f%% de NA\n", mean(resultats$pct_na)))
cat(sprintf("Maximum           : %.1f%% (le %s)\n",
            max(resultats$pct_na),
            format(resultats$date[which.max(resultats$pct_na)], "%d/%m/%Y")))
cat(sprintf("Minimum           : %.1f%% (le %s)\n",
            min(resultats$pct_na),
            format(resultats$date[which.min(resultats$pct_na)], "%d/%m/%Y")))

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# GRAPHIQUE 1 : % NA par jour (barplot)
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

nom_mois_fr <- c("Janvier","Février","Mars","Avril","Mai","Juin",
                 "Juillet","Août","Septembre","Octobre","Novembre","Décembre")

p_barre <- ggplot(resultats, aes(x = date, y = pct_na,
                                 fill = pct_na)) +
  geom_col(width = 0.8) +
  geom_hline(yintercept = mean(resultats$pct_na),
             linetype = "dashed", colour = "red", linewidth = 0.8) +
  annotate("text",
           x     = min(resultats$date),
           y     = mean(resultats$pct_na) + 1,
           label = sprintf("Moy. %.1f%%", mean(resultats$pct_na)),
           colour = "red", hjust = 0, size = 3.5) +
  scale_fill_gradient(low = "#d4e9f7", high = "#08306b",
                      name = "% NA") +
  scale_x_date(date_breaks = "5 days",
               date_labels = "%d",
               expand = c(0.02, 0)) +
  scale_y_continuous(limits = c(0, 100),
                     labels = function(x) paste0(x, "%")) +
  labs(
    title    = sprintf("%% NA E-OBS (%s) sur la France - %s %d",
                       var_diag,
                       nom_mois_fr[mois_diag],
                       annee_diag),
    subtitle = sprintf("Source : E-OBS v31.0e 0.1° | %d jours analysés",
                       nrow(resultats)),
    x = "Jour du mois",
    y = "Pourcentage de NA (%)"
  ) +
  theme_minimal(base_size = 12) +
  theme(
    plot.title    = element_text(face = "bold"),
    plot.subtitle = element_text(colour = "grey40"),
    legend.position = "right"
  )

print(p_barre)

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# GRAPHIQUE 2 : Carte des NA cumulés sur le mois
# (pixels toujours NA = rouge, parfois NA = orange, jamais NA = bleu)
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

cat("\nCalcul carte des NA cumulés...\n")

# Compter le nombre de jours avec NA pour chaque pixel
n_na_cumul <- app(r_france, function(x) sum(is.na(x)))
n_jours    <- nlyr(r_france)

# Convertir en % du mois
pct_na_cumul <- (n_na_cumul / n_jours) * 100

# Carte
plot(pct_na_cumul,
     main   = sprintf("E-OBS (%s) - %% jours avec NA sur la France\n%s %d",
                      var_diag, nom_mois_fr[mois_diag], annee_diag),
     col    = c("#08519c", "#2171b5", "#6baed6", "#bdd7e7",
                "#fed976", "#fd8d3c", "#d7191c"),
     breaks = c(0, 1, 2, 5, 10, 30, 60, 100),
     legend = TRUE)

# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????
# SAUVEGARDE
# ??????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????????

# Barplot
f_barre <- file.path(dir_out,
                     sprintf("NA_barplot_%s_%d_%02d.png",
                             var_diag, annee_diag, mois_diag))
ggsave(f_barre, plot = p_barre, width = 10, height = 5, dpi = 150)

# Tableau CSV
f_csv <- file.path(dir_out,
                   sprintf("NA_tableau_%s_%d_%02d.csv",
                           var_diag, annee_diag, mois_diag))
write.csv(resultats, f_csv, row.names = FALSE)

cat(sprintf("\n??? Barplot sauvegardé : %s\n", basename(f_barre)))
cat(sprintf("??? Tableau CSV       : %s\n", basename(f_csv)))
cat(sprintf("??? Dossier           : %s\n", dir_out))